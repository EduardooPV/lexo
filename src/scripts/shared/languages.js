const NAMES = new Map(LANGUAGES.map(({ code, name }) => [code, name]));
const BASE_NAMES = new Map([['EN', 'English'], ['PT', 'Portuguese'], ['ZH', 'Chinese']]);

export function baseOf(code) {
  return (code || '').toUpperCase().split('-')[0];
}

export function languageName(code) {
  const normalized = (code || '').toUpperCase();
  const base = baseOf(normalized);
  return NAMES.get(normalized) || BASE_NAMES.get(base) || NAMES.get(base) || code || '';
}
